SET NAMES utf8mb4;
ALTER TABLE rental_order_events MODIFY event_type ENUM('ORDER_CREATED','PAYMENT_CONFIRMED','HANDOVER','RETURN_REQUESTED','RETURN_APPROVED','RETURN_DECLINED','RETURN_RECEIVED','CLEANED','DEPOSIT_REFUNDED','ORDER_CANCELLED') NOT NULL;
CREATE TABLE IF NOT EXISTS customer_return_requests (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    order_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    location_id BIGINT UNSIGNED NOT NULL,
    status ENUM('PENDING','APPROVED','DECLINED','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
    customer_note VARCHAR(500),
    staff_note VARCHAR(500),
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at DATETIME,
    processed_by BIGINT UNSIGNED,
    FOREIGN KEY(order_id) REFERENCES rental_orders(id) ON DELETE CASCADE,
    FOREIGN KEY(user_id) REFERENCES users(id),
    FOREIGN KEY(location_id) REFERENCES locations(id),
    FOREIGN KEY(processed_by) REFERENCES users(id) ON DELETE SET NULL,
    INDEX(order_id,status),
    INDEX(location_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
